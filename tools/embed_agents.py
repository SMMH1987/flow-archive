"""Embed agents/*/ (flow.c4, rules.yaml, questionnaire, orgs, profiles, subflows) into the studio page as JSON.

The studio is one HTML file and cannot read repo files at runtime, so the data block is GENERATED
from agents/ (single source of truth). Never edit the block by hand.
  python tools/embed_agents.py          # write
  python tools/embed_agents.py --check  # exit 1 if the page is stale
"""
from __future__ import annotations

import json, pathlib, re, sys
import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
PAGE = ROOT / "docs/mockups/org-flow-artifact.html"
OPEN, CLOSE = '<script type="application/json" id="agents-data">', "</script>"
LINE = re.compile(r"^\s*(step|decision)\s+(\w+)\s+'([^']*)'(.*)$")
META = re.compile(r"(\w+)\s+'([^']*)'")


def parse_c4(text: str) -> list[dict]:
    out = []
    for ln in text.splitlines():
        m = LINE.match(ln)
        if not m:
            continue
        kind, sid, title, rest = m.groups()
        meta = dict(META.findall(rest))
        out.append({"id": sid, "kind": kind, "title": title, **meta, "gate_tag": "#gate" in rest})
    return out


def load_yaml_dir(d: pathlib.Path) -> dict:
    return {p.stem: yaml.safe_load(p.read_text(encoding="utf-8")) for p in sorted(d.glob("*.yaml"))} if d.is_dir() else {}


def collect() -> dict:
    agents = {}
    for a in sorted((ROOT / "agents").iterdir()):
        if not (a / "flow.c4").exists():
            continue
        name = re.search(r"agent\s+\w+\s+'([^']*)'", (a / "flow.c4").read_text(encoding="utf-8"))
        agents[a.name] = {
            "name": name.group(1) if name else a.name,
            "flow": parse_c4((a / "flow.c4").read_text(encoding="utf-8")),
            "subflows": {p.stem: {"name": (re.search(r"subflow\s+\w+\s+'([^']*)'", p.read_text(encoding="utf-8")) or [None, p.stem])[1],
                                  "flow": parse_c4(p.read_text(encoding="utf-8"))}
                         for p in sorted((a / "subflows").glob("*.c4"))},
            "rules": yaml.safe_load((a / "rules.yaml").read_text(encoding="utf-8"))["tables"],
            "questions": yaml.safe_load((a / "questionnaire.yaml").read_text(encoding="utf-8"))["questions"],
            "orgs": load_yaml_dir(a / "orgs"),
            "profiles": load_yaml_dir(a / "profiles"),
        }
    return {"source": "agents/ (generated by tools/embed_agents.py)", "agents": agents}


def render(page: str) -> str:
    data = json.dumps(collect(), ensure_ascii=False, separators=(",", ":"))
    i = page.index(OPEN) + len(OPEN)
    j = page.index(CLOSE, i)
    return page[:i] + data + page[j:]


def main() -> int:
    page = PAGE.read_text(encoding="utf-8")
    new = render(page)
    if "--check" in sys.argv:
        if new != page:
            print("stale: run python tools/embed_agents.py")
            return 1
        print("ok")
        return 0
    PAGE.write_text(new, encoding="utf-8")
    print("wrote", PAGE.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
